"""One editable expression table -> browser definitions and firmware constants."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ORDER=['idle','working','needs_input','message','finished','error','interrupted','disconnected']


def generate():
    data=json.loads((ROOT/'expressions'/'definitions.json').read_text(encoding='utf-8'))
    assert [s['id'] for s in data['states']]==ORDER
    for state in data['states']:
        assert 3<=state['h']<=48 and 8<=state['w']<=32
        assert len(state['cue'])<=3 and all(100<=n<=3000 for n in state['cue'])
    (ROOT/'preview').mkdir(exist_ok=True)
    (ROOT/'preview'/'definitions.mjs').write_text('// Generated by expressions/generate.py\nexport default '+json.dumps(data,indent=2)+';\n',encoding='utf-8')
    rows=[]
    for s in data['states']:
        cue=s['cue']+[0]*(3-len(s['cue']))
        rows.append('  {'+', '.join(str(s[k]).lower() for k in ['w','h','bend','gaze','breathe','blink','mouth','brow','icon'])+', {'+', '.join(map(str,cue))+'}, '+str(len(s['cue']))+'}')
    header='''// Generated by expressions/generate.py. Edit expressions/definitions.json instead.
#pragma once
#include <cstdint>
struct FaceDefinition { float w,h,bend,gaze,breathe; bool blink; float mouth,brow; uint8_t icon; uint16_t cue[3]; uint8_t notes; };
constexpr uint32_t FACE_TRANSITION_MS = '''+str(data['transitionMs'])+''';
constexpr FaceDefinition FACE_DEFINITIONS[8] = {
'''+',\n'.join(rows)+'\n};\n'
    (ROOT/'firmware'/'include'/'face_definitions.h').write_text(header,encoding='utf-8')
    print('Generated browser and firmware expression tables.')


if __name__=='__main__': generate()
