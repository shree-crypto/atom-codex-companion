"""Embed the five fixed Naruto crew WAVs and generate matching browser metadata."""
from pathlib import Path
import hashlib
import json
import wave

ROOT = Path(__file__).resolve().parents[1]
STATES = ('working', 'needs_input', 'message', 'finished', 'error')
pack = json.loads((ROOT / 'expressions/device_voice_pack.json').read_text(encoding='utf-8'))
assert set(pack['states']) == set(STATES)
lines = ['// Generated by expressions/generate_device_audio.py.',
         '// Third-party dialogue sources: expressions/device_voice_pack.json; not CC0.',
         '#pragma once', '#include <Arduino.h>']
for state in STATES:
    row = pack['states'][state]
    path = ROOT / 'preview/voices' / row['file']
    data = path.read_bytes()
    assert hashlib.sha256(data).hexdigest() == row['sha256'], state
    with wave.open(str(path), 'rb') as audio:
        assert audio.getframerate() == 16000 and audio.getnchannels() == 1
        assert audio.getsampwidth() == 2 and audio.getcomptype() == 'NONE'
        assert 0 < audio.getnframes() <= 16000 * 12
    lines.append('const uint8_t VOICE_' + state.upper() + '[] PROGMEM = {')
    lines.extend('  ' + ','.join(f'0x{v:02x}' for v in data[i:i+24]) + ',' for i in range(0, len(data), 24))
    lines.append('};')
(ROOT / 'firmware/include/voice_assets.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
(ROOT / 'preview/device-voices.mjs').write_text('// Generated by expressions/generate_device_audio.py.\nexport const deviceVoicePack=' + json.dumps(pack, indent=2) + ';\n', encoding='utf-8')
print('Generated fixed Naruto crew device voices and browser metadata.')
