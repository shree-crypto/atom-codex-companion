"""Embed the selected CC0 Cute recordings in the device firmware."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATES = ('working', 'needs_input', 'message', 'finished', 'error')
lines = ['// Generated by expressions/generate_device_audio.py.',
         '// CC0 audio credits: preview/voices/CREDITS.md',
         '#pragma once', '#include <Arduino.h>']
for state in STATES:
    data = (ROOT / 'preview/voices/cute' / (state + '.wav')).read_bytes()
    assert data[:4] == b'RIFF' and data[8:12] == b'WAVE'
    lines.append('const uint8_t VOICE_' + state.upper() + '[] PROGMEM = {')
    lines.extend('  ' + ','.join(f'0x{v:02x}' for v in data[i:i+24]) + ',' for i in range(0, len(data), 24))
    lines.append('};')
(ROOT / 'firmware/include/voice_assets.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('Generated five device WAV assets; credits retained in preview/voices/CREDITS.md.')
